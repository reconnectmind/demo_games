import { CascadedShadowGenerator } from "@babylonjs/core/Lights/Shadows/cascadedShadowGenerator";
import { ShadowGenerator } from "@babylonjs/core/Lights/Shadows/shadowGenerator";
import type { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import type { AbstractMesh } from "@babylonjs/core/Meshes/abstractMesh";

/**
 * Тени от солнца.
 *
 * До этого их в сцене не было вовсе, и лес от этого читался наклейками: дерево
 * стояло на траве, ничего на неё не роняя, а разнотон между соседними деревьями
 * шёл от случайного оттенка на экземпляр — то есть был ничем не мотивирован.
 * Именно так это и выглядело: цвета выбраны наугад. Тень мотивирует всё разом —
 * и пятно под кроной, и то, что одно дерево темнее другого.
 *
 * Карта каскадная. Обычная одна на всю видимую даль дала бы либо мыло под
 * колёсами, либо резкую границу в двадцати метрах: у нас в кадре и приборная
 * машина в трёх метрах, и лес в полутора сотнях. Каскады делят это на два
 * диапазона со своим разрешением каждый.
 *
 * Дальность намеренно короткая. Тень имеет смысл там, где видно её форму, а на
 * ста метрах крона всё равно смазана в пятно; зато каждый лишний метр дальности
 * — это лишние деревья, которые надо целиком отрисовать в карту глубины ещё раз
 * на каждый каскад. Ограничение по дальности — единственная ручка, которой эта
 * цена регулируется: тонкие экземпляры отсекаются по общей коробке всего леса, а
 * не поштучно, поэтому «нарисовать только ближние деревья» иначе не выходит.
 */
/**
 * Разрешение карты. Тысяча двадцать четыре на ближний каскад — это примерно
 * пятнадцать сантиметров на пиксель, и колесо шириной в четверть метра
 * укладывалось в полтора пикселя: тень под машиной выходила кляксой без формы, и
 * машина от этого читалась висящей. Две тысячи на каскад стоят вчетверо больше
 * памяти карты (16 МБ против четырёх) и нисколько — времени: рисуется в неё
 * ровно та же геометрия.
 */
const SIZE = 2048;
const CASCADES = 2;
const MAX_Z = 65;

export interface Shadows {
  cast(mesh: AbstractMesh): void;
  dispose(): void;
}

export function createShadows(sun: DirectionalLight): Shadows {
  const csm = new CascadedShadowGenerator(SIZE, sun);
  csm.numCascades = CASCADES;
  csm.shadowMaxZ = MAX_Z;
  // Каскады привязаны к сетке карты, а не к камере: без этого тень ползёт по
  // траве при каждом движении, и трава кипит.
  csm.stabilizeCascades = true;
  csm.lambda = 0.7;
  csm.depthClamp = true;
  csm.autoCalcDepthBounds = false;
  csm.filter = ShadowGenerator.FILTER_PCF;
  csm.filteringQuality = ShadowGenerator.QUALITY_LOW;
  // Листва — вырезанная по альфе картинка, и в карту глубины она должна попасть
  // тоже вырезанной: иначе крона отбрасывает тень сплошным прямоугольником.
  csm.transparencyShadow = true;
  /**
   * Смещение. Без него ствол и трава покрываются полосами от собственной тени, с
   * избытком — тень отрывается от предмета: пятно уезжает из-под колеса, и
   * машина повисает над дорогой. Это второй раз, когда всё выглядело так, будто
   * тени нет вовсе, — на деле она была, но в полуметре в стороне.
   *
   * Правильный порядок величины задаёт размер пикселя карты: на ближнем каскаде
   * это сантиметров семь, и смещать надо на доли этого, а не на два сантиметра.
   */
  csm.bias = 0.002;
  csm.normalBias = 0.006;
  return {
    cast(mesh) {
      csm.addShadowCaster(mesh, false);
    },
    dispose() {
      csm.dispose();
    },
  };
}
