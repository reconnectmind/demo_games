/**
 * Часы кадра: по какому времени картинка смешивает состояния физики.
 *
 * Задача выглядит тривиальной ровно до первого замера. Физика шагает по одной
 * шестидесятой секунды, ядро тикает раз в шестнадцать миллисекунд, экран
 * обновляется своим темпом, и все три частоты между собой несоизмеримы. Поэтому
 * на части тиков физика не двигается вовсе, а на части делает два шага — и если
 * считать долю смешивания от времени ядра или от времени прихода состояния,
 * скорость машины в кадре начинает пульсировать: кадр стоим, кадр едем вдвое. На
 * глаз это подрагивание вперёд-назад пару раз в секунду, и физикой оно не
 * лечится, потому что сама физика гладкая.
 *
 * Лечится это разделением времён. Состояние приходит со своим временем — числом
 * сделанных шагов, — а часы кадра идут ровно, от реального времени между кадрами,
 * и лишь медленно подстраиваются под физику изменением темпа, а не прыжком.
 *
 * Два состояния для этого мало, и это главное, что здесь неочевидно. Ядро отдаёт
 * шаги неровно: между двумя соседними шагами физики проходит то шестнадцать
 * миллисекунд, то тридцать два, потому что тик, на котором накопитель не добрал до
 * шага, не даёт ничего. Держи мы только последнюю пару, часы за такую паузу
 * доходили бы до её конца и упирались — то есть ровно то же дрожание, только реже.
 * Поэтому состояния лежат очередью, часы идут на два шага позади последнего, и
 * смешивается та пара, внутри которой они сейчас находятся: запаса в тридцать три
 * миллисекунды хватает на любую паузу доставки, какую способно дать ядро.
 *
 * Задержка картинки от этого — те же тридцать три миллисекунды, два кадра на
 * шестидесяти герцах. Её не замечает никто; пульсацию скорости замечают все.
 */

/** Шаг физики, секунды. */
const STEP_S = 1 / 60;
/** На сколько кадр отстаёт от последнего состояния: две паузы доставки с запасом. */
const LAG_S = 2 * STEP_S;
/**
 * Насколько сильно расхождение меняет темп часов: расхождение в одну десятую
 * секунды и больше даёт предельные пятнадцать процентов. Больше брать нельзя —
 * ускорение картинки становится видно само по себе.
 */
const TRIM = 0.15;
const TRIM_FULL_S = 0.1;
/**
 * Расхождение, после которого часы не подстраивают, а переставляют: свёрнутая
 * вкладка, пауза, возобновление из снимка. Догонять секунды темпом бессмысленно.
 */
const SNAP_S = 0.25;
/** Длина очереди: с запасом к тому, что нужно при задержке в два шага. */
const KEPT = 8;
/**
 * Сглаживание темпа кадров.
 *
 * Экран обновляется по линейке — шестьдесят раз в секунду, — а вот **замер** этого
 * промежутка по линейке не идёт: наш обработчик браузер зовёт то на миллисекунду
 * раньше, то на три позже, и намеренная пауза тут ни при чём. Живой замер даёт
 * от 12.9 до 20.3 миллисекунды при медиане 16.7, то есть плюс-минус пятую часть.
 *
 * Двигать мир на измеренную величину — значит внести эту пятую часть прямо в
 * скорость картинки: кадр мир едет на пятую часть быстрее, кадр на столько же
 * медленнее, а показывается всё это через ровные шестнадцать миллисекунд. На глаз
 * это и есть подрагивание вперёд-назад на ходу, и оно тем заметнее, чем быстрее
 * едешь: на ста километрах в час пятая часть кадра — это двадцать сантиметров.
 *
 * Поэтому часы идут не на измеренный промежуток, а на сглаженный — и это не
 * подгонка: настоящий промежуток между показами как раз постоянный, а шумит
 * именно замер. За то, чтобы сглаженный темп не уплыл от настоящего, отвечает та
 * же подстройка по расхождению с физикой, что и раньше.
 */
const PACE_BLEND = 0.06;
/**
 * Когда темп не сглаживают, а переставляют. Шум замера держится в пятой части, а
 * настоящая смена частоты экрана (шестьдесят на тридцать, переезд на другой
 * монитор) — это сразу вдвое. Треть отделяет одно от другого с запасом в обе
 * стороны, а требование повторить это несколько кадров подряд отсекает
 * одиночную заминку, после которой темп остался прежним.
 */
const PACE_GATE = 1.35;
const PACE_PATIENCE = 3;

/** Что показывать в кадре: смесь двух состояний в долях. */
export interface Blend<T> {
  from: T;
  to: T;
  /** Ноль — ровно `from`, единица — ровно `to`. */
  alpha: number;
}

interface Held<T> {
  state: T;
  /** Время физики, секунды. */
  t: number;
}

export class Playout<T> {
  /** Состояния по возрастанию времени физики. */
  private ring: Held<T>[] = [];
  /** Часы кадра во времени физики, секунды. */
  private clock = 0;
  /** Сглаженный промежуток между кадрами, секунды. Ноль — ещё ни одного кадра. */
  private paced = 0;
  /** Сколько кадров подряд замер не похож на сглаженный темп. */
  private odd = 0;

  /**
   * Пришло состояние физики. Тик, на котором физика не двигалась, приходит с тем
   * же временем и очередь не удлиняет: нового положения в нём нет.
   */
  arrive(state: T, t: number): void {
    const newest = this.ring[this.ring.length - 1];
    if (!newest) {
      this.ring.push({ state, t });
      this.clock = t - LAG_S;
      return;
    }
    if (t === newest.t) return;
    if (t < newest.t) {
      // Мир пересобрали: снимок, повтор журнала, смена уровня. Смешивать нечего.
      this.ring = [{ state, t }];
      this.clock = t - LAG_S;
      return;
    }
    this.ring.push({ state, t });
    if (this.ring.length > KEPT) this.ring.shift();
  }

  /**
   * Сглаженный темп кадров: на него же надо равнять и всё остальное, что в кадре
   * считается по времени, — иначе камера втянет тот самый шум замера обратно.
   */
  pace(): number {
    return this.paced;
  }

  /** Сдвинуть часы на прошедшее реальное время и сказать, что показывать. */
  at(dtS: number): Blend<T> | null {
    const newest = this.ring[this.ring.length - 1];
    if (!newest) return null;
    this.keepPace(Math.max(0, dtS));
    const target = newest.t - LAG_S;
    const drift = target - this.clock;
    if (Math.abs(drift) > SNAP_S) this.clock = target;
    else {
      const share = Math.max(-1, Math.min(1, drift / TRIM_FULL_S));
      this.clock += this.paced * (1 + share * TRIM);
    }
    // Впереди последнего состояния показывать нечего: физика туда ещё не дошла,
    // а гадать о будущем дороже, чем на мгновение постоять.
    if (this.clock > newest.t) this.clock = newest.t;

    // Отпускаем всё, что уже позади: пара для смешивания — та, внутри которой часы.
    while (this.ring.length > 2 && this.ring[1]!.t <= this.clock) this.ring.shift();
    const from = this.ring[0]!;
    const to = this.ring[1] ?? from;
    const span = to.t - from.t;
    const alpha = span <= 0 ? 0 : Math.max(0, Math.min(1, (this.clock - from.t) / span));
    return { from: from.state, to: to.state, alpha };
  }

  /** Обновить сглаженный темп по свежему замеру промежутка. */
  private keepPace(dtS: number): void {
    if (this.paced <= 0 || dtS <= 0) {
      this.paced = dtS > 0 ? dtS : this.paced;
      return;
    }
    const off = dtS / this.paced;
    this.odd = off > PACE_GATE || off < 1 / PACE_GATE ? this.odd + 1 : 0;
    if (this.odd >= PACE_PATIENCE) {
      // Экран правда сменил частоту — тянуть темп к ней по проценту за кадр
      // значило бы секунду ехать в долгу, а долг потом отдаётся ускорением.
      this.paced = dtS;
      this.odd = 0;
      return;
    }
    // Одиночная заминка учитывается вполсилы: темп от неё не должен уехать.
    const seen = Math.min(this.paced * 2, Math.max(this.paced * 0.5, dtS));
    this.paced += (seen - this.paced) * PACE_BLEND;
  }
}
