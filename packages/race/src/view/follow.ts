/**
 * Насколько камера смещается вбок вслед за машиной.
 *
 * Задача с двумя концами. Внутри полосы камера должна идти за машиной **не до
 * конца**: если она держит машину строго по центру кадра, дорога перестаёт ездить
 * относительно неё, и вместо езды по полосе видно только руль. Снаружи — наоборот,
 * идти надо один к одному: на большом съезде машина иначе уходит к краю кадра, а
 * потом и вовсе из него, и участник смотрит на пустую траву.
 *
 * Первая версия сшивала два этих правила встык: до кромки асфальта половина
 * смещения, за кромкой единица. Формула короткая, а на глаз — рывок ровно в тот
 * момент, когда колесо пересекает кромку: скорость, с которой машина едет по кадру,
 * мгновенно меняется вдвое. Заметно это как раз тогда, когда через кадр проезжают
 * поперёк — от левой обочины к правой, — и рывков выходит два, по одному на кромку.
 * Замер: угловая скорость машины в кадре падала с 15.6 до 7.0 градусов в секунду за
 * один кадр.
 *
 * Лечится не сглаживанием (сглаживание запаздывает и на быстром съезде теряет
 * машину), а тем, что стык убирается вовсе. Гиперболический тангенс даёт ровно те
 * же два предела — половину в середине полосы и единицу вдали, — но переходит между
 * ними плавно, и производная нигде не прыгает.
 */

/** Доля смещения в середине полосы: камера идёт за машиной вполовину. */
const NEAR = 0.5;

export function cameraFollow(lateral: number, halfWidth: number): number {
  if (halfWidth <= 0) return lateral;
  return lateral - NEAR * halfWidth * Math.tanh(lateral / halfWidth);
}
