/**
 * Сочленения дерева: сколько подвижности показывать на каком расстоянии.
 *
 * Дерево — не одно тело, а цепочка: ствол, ветка, прут, черешок, лист. Считать
 * все звенья всегда — расточительно и, что важнее, вредно. Лист вдали занимает
 * меньше пикселя; собственное движение такого листа не видно как движение, оно
 * видно как мерцание — вершина скачет между соседними пикселями, и крона
 * начинает шипеть. Поэтому вдали дерево качается крупно, целыми ветками, а
 * ближние звенья включаются по мере приближения.
 *
 * Здесь только числа и кривая. Само качание живёт в вершинном шейдере
 * (`wind.ts`), а шейдер тестом не проверишь — но выбор «сколько подвижности на
 * этом расстоянии» проверить можно и нужно, потому что ошибка в нём выглядит
 * либо шипящей кроной, либо картонным лесом в двух шагах от машины.
 *
 * Модуль без единой ссылки на Babylon — по той же причине, что и `plant.ts`.
 */

/**
 * Дальше этого сочленения не шевелятся вовсе, метры.
 *
 * Взято по кроне, а не по стволу: на полусотне метров лист занимает доли
 * пикселя, и его собственный ход уже не различить среди листьев рядом.
 */
export const JOINT_FAR_M = 45;
/** Ближе этого показывается вся подвижность, какая есть, метры. */
export const JOINT_NEAR_M = 12;

/**
 * Доля подвижности мелких звеньев на этом расстоянии: 0 — только ветка,
 * 1 — лист живёт сам по себе.
 *
 * Кривая гладкая (это `smoothstep`), и гладкость тут не украшение: на изломе
 * было бы видно кольцо вокруг машины, внутри которого лес вдруг оживает.
 */
export function jointDetail(distanceM: number): number {
  const span = JOINT_FAR_M - JOINT_NEAR_M;
  const t = Math.max(0, Math.min(1, (distanceM - JOINT_NEAR_M) / span));
  return 1 - t * t * (3 - 2 * t);
}

/** Вершин на лист: четыре угла и поднятая над ними середина (см. печать). */
export const LEAF_VERTS = 5;

/**
 * Ось листа: его середина, повторённая во всех пяти его вершинах.
 *
 * Вокруг неё лист и поворачивается. Середина, а не черешок, — сознательно: где
 * у испечённого листа основание, геометрия не помнит, а поворот вокруг середины
 * не таскает лист по кроне. Лист крутится там, где висит, силуэт кроны от этого
 * не плывёт, и при этом он всё время показывает то плоскость, то ребро — а
 * именно эта смена и читается как живой лист.
 *
 * Ось нужна ещё и вторым делом: из неё шейдер берёт фазу трепета. Одна ось на
 * лист — значит одна фаза на лист, и лист ходит целиком, а не дышит на месте.
 */
export function leafPivots(positions: Float32Array): Float32Array {
  const count = positions.length / 3;
  const out = new Float32Array(count * 3);
  for (let leaf = 0; leaf * LEAF_VERTS < count; leaf++) {
    const mid = (leaf * LEAF_VERTS + 4) * 3;
    const x = positions[mid]!;
    const y = positions[mid + 1]!;
    const z = positions[mid + 2]!;
    for (let i = 0; i < LEAF_VERTS; i++) {
      const at = (leaf * LEAF_VERTS + i) * 3;
      out[at] = x;
      out[at + 1] = y;
      out[at + 2] = z;
    }
  }
  return out;
}
