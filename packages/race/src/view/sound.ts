/**
 * Звук заезда — но только решение о том, что должно звучать. Ни одного узла Web
 * Audio здесь нет, и это нарочно: смешивание — арифметика, а арифметику надо
 * проверять тестом, а не ухом в браузере.
 *
 * Слышно должно быть ровно то, что машина делает, и в первую очередь то, чего не
 * видно. Обороты глазами читаются с тахометра, а вот сорвались ли колёса, какое
 * покрытие под ними и близко ли шина к пределу — глазами не читается никак.
 * Поэтому звук здесь не украшение, а второй прибор: по нему слышно передачу не
 * ту, срыв, съезд на гравий и то, что газ уходит в дым вместо движения.
 *
 * Три голоса, и каждый отвечает за своё:
 *
 * - **мотор** — обороты и нагрузка. Тон рождается из последовательности вспышек
 *   (см. «Выхлоп» ниже), а нагрузка слышна не громкостью, а яркостью: под
 *   нагрузкой выхлоп звенит обертонами, на сбросе оседает в глухое бормотание;
 * - **качение** — покрытие и скорость. Асфальт шипит высоко, гравий гремит
 *   громче и злее, трава глухо шуршит. Это единственный способ услышать, что
 *   два колеса уже на обочине, а два ещё нет;
 * - **срыв** — проскальзывание. Начинается ровно там, где кончается держащая
 *   часть кривой шины, и поэтому визг означает не «водитель шумит», а «шина
 *   отдала всё, что могла».
 *
 * Плюс ветер, который просто растёт со скоростью и держит ощущение хода.
 */

