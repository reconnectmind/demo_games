import { WHEELBASE_M } from "./geometry.js";

/**
 * Руль: не положение, а состояние, у которого своя динамика.
 *
 * Первая версия считала клавишу заданием угла: нажал — угол едет к пределу,
 * отпустил — тем же темпом обратно к нулю. Это не руль, а тумблер, и заметно это
 * именно на скорости: в жизни отпущенный руль возвращается сам и тем быстрее,
 * чем быстрее едешь, а на месте остаётся там, где его бросили. Разница не
 * косметическая — на ней держится вся техника руления: в повороте руль
 * подхватывают, а не выкручивают обратно.
 *
 * Модель самая простая из честных. Руки дают постоянную скорость поворота рейки,
 * колёса — возвращающий момент, пропорциональный углу и **квадрату** скорости
 * (боковая сила шины растёт с квадратом скорости, а плечо у неё — вынос шкворня
 * и увод пятна контакта):
 *
 *     dδ/dt = вход · RACK_RATE − k(v) · δ,   k(v) = CENTER · v²
 *
 * Отсюда сразу два свойства, ради которых всё и делалось. На месте `k` равен
 * нулю: руль стоит где поставили. На ходу равновесие `δ = RACK_RATE / k(v)`
 * падает как квадрат скорости — то есть при постоянном усилии рук машина идёт по
 * дуге примерно постоянного бокового ускорения, что и происходит в жизни.
 */
const RACK_RATE = 1.7;
/**
 * Механический предел рейки. До него дело доходит только на ползущей машине: на
 * ходу руль раньше упирается в собственный возврат.
 */
export const STEER_LOCK = 0.5;
/**
 * Боковое ускорение, на которое рассчитан возврат: при полном усилии рук машина
 * выходит примерно на него и не срывается в разворот. Три четверти g — это
 * уверенный поворот на сухом асфальте, дальше начинается снос.
 */
const HOLD_ACCEL_MS2 = 0.75 * 9.81;
/**
 * Жёсткость возврата подобрана так, чтобы равновесие при полном усилии совпало с
 * углом на `HOLD_ACCEL_MS2`: RACK_RATE / (CENTER·v²) = база·a/v². Скорость из
 * равенства уходит — коэффициент получается один на все скорости.
 */
const CENTER = RACK_RATE / (WHEELBASE_M * HOLD_ACCEL_MS2);
/**
 * Как быстро рейка вообще способна переложиться, рад/с.
 *
 * Раньше на этом месте стоял верхний предел жёсткости возврата, и стоял он не
 * там. Задача была одна: на ста километрах в час постоянная времени возврата —
 * три сотых секунды, и руль не возвращается, а щёлкает. Но потолок жёсткости
 * гасит заодно и равновесие: `RACK_RATE/k` перестаёт падать со скоростью, и
 * выше десяти метров в секунду полное усилие рук даёт одиннадцать градусов на
 * любой скорости — что на пятидесяти километрах в час, что на ста тридцати. На
 * ста тридцати это полтора же в развороте от одного нажатия клавиши.
 *
 * Мешают рулю трение в рейке и масса рук — а они ограничивают **скорость**
 * перекладки, а не угол, на котором усилия уравновешиваются. Поэтому жёсткость
 * снова растёт с квадратом скорости, как ей и положено, а ограничение стоит
 * там, где ему место: рейка не переложится быстрее, чем позволяют руки.
 */
const RACK_SLEW = 3;

/**
 * ## Руль отсчитывается не от кузова, а от того, куда едет передняя ось
 *
 * Всё выше молча полагает, что машина едет туда, куда смотрит. Пока держат
 * шины, так и есть, и разница между «углом колёс относительно кузова» и «углом
 * колёс относительно набегающей дороги» лежит в пределах пары градусов. В
 * заносе она равна всему: кузов развёрнут поперёк, передние колёса едут вбок
 * сами по себе, и угол, при котором они катятся ровно, — это уже не ноль.
 *
 * Отсюда две вещи, которых у руля не было и без которых заносом нельзя ни
 * управлять, ни выйти из него.
 *
 * Первая: **руль возвращается не в ноль, а в снос**. Стабилизирующий момент
 * стремится обнулить увод шины, а не угол рейки, — поэтому брошенный в заносе
 * руль сам перекладывается в контрруль, и машина ловит себя. Это не поблажка
 * игроку, это то, что происходит в жизни и почему в заносе руль отпускают.
 *
 * Вторая: **отдельного предела угла больше нет**. Он был нужен, пока равновесие
 * рейки отсчитывалось от нуля: на скорости `RACK_RATE/k` — это те самые
 * полтора-два градуса, и всё, что человек мог сделать клавишей, укладывалось в
 * них, а предел стоял ровно затем, чтобы резкий бросок руля не успел проскочить
 * дальше равновесия. Теперь равновесие отсчитывается от сноса и означает нечто
 * определённое: угол увода передних колёс, на котором постоянное усилие рук
 * уравновешивается стабилизирующим моментом. Выходит около одиннадцати градусов
 * — чуть за пиком шины, то есть «руль до упора» и означает «передок отдал всё».
 * Больше этого рейка не уйдёт сама, а меньше её незачем ограничивать: в заносе
 * ограничивать надо было бы как раз контрруль, а он-то и нужен.
 */

/**
 * Куда едет передняя ось относительно кузова, радианы. При таком угле рейки
 * передние колёса катятся без увода вовсе.
 */
export function steerNeutral(latMs: number, longMs: number): number {
  return Math.atan2(latMs, Math.max(Math.abs(longMs), 3));
}

/**
 * Куда руль придёт при постоянном полном усилии рук на этой скорости, отсчитывая
 * от сноса: равновесие рейки против стабилизирующего момента. Механический упор
 * рейки его обрезает — на ползущей машине равновесия нет вовсе.
 */
export function steerLimit(speedMs: number): number {
  const v = Math.abs(speedMs);
  const k = CENTER * v * v;
  if (k < 1e-4) return STEER_LOCK;
  return Math.min(STEER_LOCK, RACK_RATE / k);
}

/**
 * Шаг руля. Решение считается точно по экспоненте, а не шагом Эйлера: на ста
 * километрах в час `k·dt` подбирается к единице, и явный шаг начинает
 * раскачиваться там, где руль обязан успокаиваться.
 *
 * `neutral` — угол, при котором передние колёса не уводит (`steerNeutral`). На
 * прямой он нуль, и тогда всё считается ровно так, как считалось.
 */
export function steerStep(angle: number, input: number, speedMs: number, dtS: number, neutral = 0): number {
  const drive = Math.max(-1, Math.min(1, input)) * RACK_RATE;
  const v = Math.abs(speedMs);
  const k = CENTER * v * v;
  const rest = neutral + drive / k;
  // Стоячая машина: возвращать нечему, руль просто едет от рук.
  const free = k * dtS < 1e-4 ? angle + drive * dtS : rest + (angle - rest) * Math.exp(-k * dtS);
  const slew = RACK_SLEW * dtS;
  const next = Math.max(angle - slew, Math.min(angle + slew, free));
  return Math.max(-STEER_LOCK, Math.min(STEER_LOCK, next));
}
