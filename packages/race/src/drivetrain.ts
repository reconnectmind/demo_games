/**
 * Силовой агрегат: обороты, момент, передачи. Отдельно от физики кузова, потому
 * что физический движок принимает на входе одну силу на колесе и про двигатель
 * не знает ничего — коробку всё равно пишем мы.
 *
 * Раньше тяга была прямо пропорциональна передаточному числу, то есть низкая
 * передача давала мало силы. В машине наоборот: низкая передача умножает момент,
 * поэтому с неё и трогаются. Из-за вывернутой модели нельзя было тронуться с
 * третьей — и это была ошибка модели, а не отсутствие движка.
 *
 * Метафора биофидбека от правильной физики только выигрывает. Низкая передача —
 * это напряжение: рвёт с места, но обороты мгновенно улетают в отсечку, шума
 * много, пути мало, мотор греется. Высокая — расслабленность: тянет мягко, зато
 * тянет долго и далеко. Ровно то же и с физиологией.
 */

import { WHEEL_RADIUS_M } from "./geometry.js";

export { WHEEL_RADIUS_M };
export const FINAL_DRIVE = 4.6;
export const RPM_IDLE = 850;
/**
 * Обороты, на которых мотор упирается в неподвижный гидротрансформатор при полном
 * газе: момент мотора ровно равен тому, что трансформатор способен проглотить.
 * Не задание для оборотов, а точка равновесия — из неё выводится жёсткость
 * трансформатора (`CONVERTER_K`), а сами обороты к ней приходят сами.
 */
export const RPM_STALL = 2400;
export const RPM_PEAK = 4200;
/** Отсечка: выше момента нет вовсе, только рёв. */
export const RPM_MAX = 7000;
/**
 * Момент под стать кузову: две с лишним тонны Cayenne на моторе от лёгкой машины
 * не едут — с прежними двумястами шестьюдесятью ньютон-метрами разгон до
 * тридцати километров в час занимал шесть секунд. У настоящего GTS около
 * пятисот, и наши четыреста двадцать возвращают ровно тот темп, под который
 * настраивались передачи и нагрев.
 */
export const TORQUE_PEAK_NM = 420;
const DRIVELINE_EFF = 0.9;

/**
 * Передаточные числа от низшей к высшей. Восемь ступеней — весь диапазон
 * вариатора; при меньшем числе ступеней берутся крайние и равномерные между ними,
 * поэтому «первая» и «последняя» всегда одинаковы на любом уровне сложности.
 */
const GEAR_TABLE = [3.6, 2.5, 1.9, 1.5, 1.22, 1.0, 0.85, 0.72];

/**
 * Селектор: задний ход, нейтраль и передачи вперёд подряд одним числом.
 *
 * Ноль отдан нейтрали не для красоты нумерации, а потому, что нейтраль — это и
 * есть нулевое передаточное отношение: на колёса не уходит ничего. Задний ход
 * при этом отрицателен по той же причине — у него вал крутится в другую
 * сторону, и одного знака достаточно, чтобы вся тяга поехала назад сама,
 * ничего больше в модели не трогая.
 */
export const GEAR_REVERSE = -1;
export const GEAR_NEUTRAL = 0;
/**
 * Задний ход, отношение. По модулю близок к первой: назад машина едет с тем же
 * умножением момента, но одной ступенью — разгоняться задом не на чем и незачем,
 * и упирается это в отсечку где-то на сорока километрах в час.
 */
export const REVERSE_RATIO = -3.4;

export function ratiosFor(gears: number): number[] {
  if (gears <= 1) return [GEAR_TABLE[GEAR_TABLE.length - 1]!];
  const out: number[] = [];
  for (let i = 0; i < gears; i++) {
    const at = Math.round((i * (GEAR_TABLE.length - 1)) / (gears - 1));
    out.push(GEAR_TABLE[at]!);
  }
  return out;
}

/** Передача селектора: −1 — назад, 0 — нейтраль, 1..gears — вперёд. */
export function ratioFor(gear: number, gears: number): number {
  if (gear <= GEAR_REVERSE) return REVERSE_RATIO;
  if (gear === GEAR_NEUTRAL) return 0;
  const ratios = ratiosFor(gears);
  return ratios[Math.min(gear, ratios.length) - 1]!;
}

function clamp(value: number, min: number, max: number): number {
  return value < min ? min : value > max ? max : value;
}

/**
 * Момент инерции всего, что вращается за колесом, приведённый к самому колесу.
 *
 * Это не украшение модели, а то, без чего колесо с честной шиной вообще не
 * считается. Колесо само по себе лёгкое, и если крутить его моментом двигателя,
 * ни с чем больше не связанным, за один шаг физики оно набирает несколько
 * метров в секунду по ободу. Проскальзывание при этом мгновенно улетает за пик
 * кривой, и шина всё время отдаёт предельную силу — то есть машина разгоняется
 * одинаково на любой передаче, а модель шины оказывается декорацией.
 *
 * На самом деле за колесом стоит коленвал, и приведённая инерция растёт с
 * квадратом передаточного числа: на первой передаче раскрутить колесо — значит
 * раскрутить мотор в шестнадцать раз быстрее. Отсюда и вся разница между
 * передачами: низкая даёт много момента, но и разгоняется тяжело, поэтому
 * сорвать колёса ей проще, а вот докрутить их до высоких оборотов — нет.
 */
const ENGINE_INERTIA = 0.22;

export function drivelineInertia(ratio: number): number {
  const total = ratio * FINAL_DRIVE;
  return (ENGINE_INERTIA * total * total) / 4;
}

/** Геометрические обороты: колёса и коленвал связаны жёстко, пока не буксует сцепление. */
export function geometricRpm(speedMs: number, ratio: number): number {
  const wheelRadS = Math.abs(speedMs) / WHEEL_RADIUS_M;
  return (wheelRadS * ratio * FINAL_DRIVE * 60) / (2 * Math.PI);
}

/**
 * Полоса, на которой ограничитель гасит подачу, об/мин.
 *
 * Отсечка не выключает мотор ножом. Она режет впрыск не весь, а вспышка через
 * вспышку, и доля срезанных растёт по мере того, как обороты лезут за предел;
 * потому мотор на ограничителе не глохнет, а стрекочет чуть выше него, отдавая
 * часть момента. Ножом это стоило машине всего разгона в единственном месте,
 * где обороты держит не водитель: стоило ведущему колесу забуксовать, как оно
 * само загоняло коленвал за предел, там момент обращался в нуль — и машина,
 * ревя на отсечке, переставала ехать вовсе. С травы после такого было не
 * выбраться.
 */
const LIMIT_BAND_RPM = 320;

/**
 * Кривая момента: растёт от холостых к максимуму, к отсечке спадает, на полосе
 * ограничителя гаснет. Спад — это и есть то, почему на низкой передаче нельзя
 * ехать быстро.
 */
export function torqueAt(rpm: number): number {
  const cut = clamp((rpm - RPM_MAX) / LIMIT_BAND_RPM, 0, 1);
  if (cut >= 1) return 0;
  const live = 1 - cut;
  if (rpm <= RPM_IDLE) return TORQUE_PEAK_NM * 0.55 * live;
  if (rpm <= RPM_PEAK) {
    const t = (rpm - RPM_IDLE) / (RPM_PEAK - RPM_IDLE);
    return TORQUE_PEAK_NM * (0.55 + 0.45 * t * (2 - t)) * live;
  }
  const t = Math.min(1, (rpm - RPM_PEAK) / (RPM_MAX - RPM_PEAK));
  return TORQUE_PEAK_NM * (1 - 0.45 * t * t) * live;
}

/** Радианы в секунду на один оборот в минуту. */
const RAD_PER_RPM = (2 * Math.PI) / 60;

/**
 * ## Обороты как физическая величина
 *
 * До сих пор обороты не считались, а назначались: брался максимум из
 * «геометрических» (колесо через передачи) и «стояночных» (полка, поднимаемая
 * газом). Получалось ровно то, на что и жалуются: газ мгновенно ставит обороты
 * на полку, отпущенный газ ничего не меняет, а падают они только когда тормоз
 * замедлит колесо. Ни маховика, ни торможения двигателем, ни отклика — обороты
 * были показанием, а не состоянием.
 *
 * Теперь коленвал — тело с моментом инерции, и у него ровно один закон:
 *
 *     I·dω/dt = момент сгорания − насосные потери + холостой регулятор − отдача трансформатора
 *
 * Всё поведение, которого не хватало, из этого выпадает само: обороты набираются
 * не мгновенно, а за время, которое маховику нужно; на сброшенном газе насосные
 * потери тормозят и мотор, и через трансмиссию машину; на месте под тормозом
 * мотор раскручивается против неподвижного трансформатора и падает обратно к
 * холостым, когда газ отпустили.
 */

/**
 * Гидротрансформатор: жидкостная связь мотора с коробкой.
 *
 * Момент, который он передаёт, растёт с квадратом разницы скоростей насоса и
 * турбины — это и есть отличие жидкости от вала. Отсюда две вещи, ради которых
 * трансформатор в машине и стоит: на месте он даёт мотору крутиться, а не
 * глохнуть, и сам собой умножает момент на трогании.
 *
 * Жёсткость не подобрана, а выведена: на неподвижной турбине при полном газе
 * равновесие обязано прийтись на `RPM_STALL` — там, где момент мотора ровно
 * равен проглатываемому. Это одно уравнение с одним неизвестным.
 */
const CONVERTER_K = torqueAt(RPM_STALL) / (RPM_STALL * RAD_PER_RPM) ** 2;
/**
 * Блокировка: муфта, которая на ходу замыкает трансформатор накоротко.
 *
 * Без неё машина едет «на жидкости»: на пяти тысячах оборотов проскальзывание
 * доходит до шестисот оборотов, мотор воет впереди скорости, а торможение
 * двигателем пропадает вовсе — жидкость плохо тянет назад.
 *
 * Замкнутая муфта — это не жёсткая пружина, а другой режим, и считать её надо
 * иначе. Пружиной пробовали: жёсткость подбирается так, чтобы проскальзывание
 * упало до процента, и на этой жёсткости первое же понижение передачи на
 * скорости выдаёт пятнадцать тысяч ньютон-метров и рвёт физику в NaN. Причём не
 * от ошибки в числе, а по существу: у пружины момент растёт с разницей
 * скоростей без предела, а у замкнутого вала разницы нет вовсе — коленвал и
 * есть турбина.
 *
 * Поэтому режима два, и они считаются по-разному. Свободный — маховик против
 * жидкости. Замкнутый — коленвал, приколоченный к трансмиссии: обороты берутся
 * от колеса, а на колёса уходит то, что мотор в самом деле производит, момент
 * сгорания за вычетом насосных потерь. Маховик в этом режиме уже висит на
 * колесе (`drivelineInertia`), и второй раз его считать не надо.
 */
/** Обороты турбины, между которыми муфта смыкается, рад/с. */
const LOCK_FROM = 1400 * RAD_PER_RPM;
const LOCK_FULL = 2400 * RAD_PER_RPM;

/**
 * Насосные потери и трение: то, чем мотор тормозит, когда газ отпущен.
 *
 * Главная их часть — работа против закрытой дроссельной заслонки, поэтому они
 * и пропадают на полном газе: заслонка открыта, качать против нечего. Это не
 * упрощение, а причина, по которой торможение двигателем есть только на
 * сброшенном газе.
 */
const PUMP_BASE_NM = 18;
const PUMP_RISE_NM = 77;

/**
 * Регулятор холостого хода: то, чем мотор не даёт себе заглохнуть.
 *
 * У него есть предел власти, и предел этот виден: на холостых в передаче
 * трансформатор тянет с мотора почти всё, что регулятор может дать, и обороты
 * проседают на полсотни. Ровно так и оседают обороты у настоящей машины, когда
 * из нейтрали переводят в драйв.
 */
const IDLE_AUTHORITY_NM = 140;
const IDLE_BAND_RPM = 120;

/**
 * Нейтраль на стоянке: пакет сцепления, разжатый на остановке с закрытым газом.
 *
 * Гидротрансформатор тянет всегда, и это его свойство, а не изъян: на холостых
 * он передаёт полсотни ньютон-метров, машина трогается сама и разгоняется, пока
 * турбина не догонит коленвал. В первой передаче это привычные шесть километров
 * в час — та самая ползучесть автомата. Но передачу здесь выбирает человек, а не
 * коробка, и во второй та же ползучесть выходит уже под четырнадцать: машина без
 * газа уезжает сама, и это читается поломкой, а не характером.
 *
 * Настоящая коробка ровно от этого и защищается. На стоянке с отпущенным газом
 * гидромеханика сбрасывает давление в пакете, и связь мотора с колёсами
 * размыкается: у ZF и Tiptronic это называется нейтралью холостого хода и
 * ставится и ради расхода, и ради того, чтобы машина не толкалась. Стоит
 * тронуть газ — пакет смыкается обратно.
 */
const CREEP_FREE_MS = 2.4;
const CREEP_PEDAL = 0.05;

/**
 * Насколько турбина отстаёт от насоса на нейтрали.
 *
 * Не ноль: масло в трансформаторе мешается всегда, и часть момента насос теряет
 * на этом даже вхолостую. Проценты отставания — это те несколько десятков
 * ньютон-метров на верхах, из-за которых мотор на нейтрали раскручивается быстро,
 * но не мгновенно.
 */
const NEUTRAL_SLIP = 0.01;

function smoothstep(value: number, from: number, to: number): number {
  const t = clamp((value - from) / (to - from), 0, 1);
  return t * t * (3 - 2 * t);
}

/** Насосные потери на этих оборотах и этом газе, Н·м. */
export function pumpingNm(rpm: number, throttle: number): number {
  const open = clamp(throttle, 0, 1);
  return (PUMP_BASE_NM + PUMP_RISE_NM * clamp(rpm / RPM_MAX, 0, 1)) * (1 - open);
}

export interface EngineIn {
  /**
   * Скорость обода ведущих колёс, м/с.
   *
   * Именно обода, а не машины: обороты держит колесо. Пока шина цепляется, это
   * одно и то же; как только ведущие сорвались, обороты уходят вверх, а машина
   * остаётся — и в заносе это слышно раньше, чем видно.
   */
  wheelSpeedMs: number;
  ratio: number;
  /** Газ, 0..1. */
  throttle: number;
  /** Потолок мощности: перегрев вынуждает успокоиться, не отнимая управление. */
  powerCap: number;
  dtS: number;
}

export interface Engine {
  /** Сила на колёсах, ньютоны: единственное, что уходит в физический движок. */
  forceN: number;
  rpm: number;
  /** Доля газа, ушедшая в обороты и проскальзывание вместо дороги: она и греет. */
  waste: number;
  /**
   * Насколько трансформатор замкнут: 0 — жидкость, 1 — вал. Физике он нужен,
   * чтобы знать, висит ли маховик на колесе: на разомкнутом трансформаторе
   * колесо лёгкое и срывается охотно, на замкнутом за ним стоит весь мотор.
   */
  lock: number;
  /** Проскальзывание трансформатора, рад/с: по нему считается и потеря, и звук. */
  slipRadS: number;
}

/**
 * Один шаг коленвала.
 *
 * Шаг неявный по отдаче трансформатора, и это не педантизм: на замкнутой муфте
 * жёсткость связи такова, что явный шаг в шестидесятую секунды раскачивается —
 * обороты начинают звенеть вокруг скорости турбины вместо того, чтобы за ней
 * следовать. Линеаризация отдачи по угловой скорости снимает это начисто и
 * стоит одного деления.
 */
export function engineStep(rpm: number, input: EngineIn): Engine {
  const dtS = Math.max(0, input.dtS);
  const pedal = clamp(input.throttle, 0, 1) * clamp(input.powerCap, 0, 1);
  const idleRad = RPM_IDLE * RAD_PER_RPM;

  // Свободный режим: маховик разгоняется тем, что осталось от момента сгорания
  // после насосных потерь и того, что забрала жидкость. Шаг неявный по отдаче
  // трансформатора — иначе на малой инерции маховика он звенит.
  const was = Math.max(idleRad * 0.5, rpm * RAD_PER_RPM);
  const wasRpm = was / RAD_PER_RPM;

  /**
   * Куда и как быстро колесо крутит турбину. Знак здесь имеет смысл: на заднем
   * ходу отношение отрицательно, и катящаяся назад машина крутит турбину в ту же
   * сторону, что и едущая вперёд на первой, — трансформатору всё равно, куда едет
   * кузов, ему важно, куда крутится вал.
   *
   * Отрицательный знак означает, что выбранная передача смотрит против хода:
   * задний ход включили на ходу вперёд или наоборот. Настоящая коробка в этот
   * момент пакет не смыкает, и не из вежливости — смыкание было бы ударом всей
   * трансмиссии наотмашь. Пока катимся не туда, связи с колёсами нет вовсе, а как
   * скорость упадёт до шага, передача возьмётся сама.
   */
  const spin = (input.wheelSpeedMs / WHEEL_RADIUS_M) * input.ratio * FINAL_DRIVE;
  const against = spin < 0 && Math.abs(input.wheelSpeedMs) > CREEP_FREE_MS;
  /**
   * Пакет разомкнут — нейтралью или блокировкой, — и турбина не привязана к колесу
   * вовсе: за ней висит один первичный вал, и она раскручивается почти вровень с
   * насосом, отставая на проценты. Отсюда и то, ради чего нейтраль нужна: мотор на
   * ней свободно уходит до отсечки, а не упирается в трансформатор, как в передаче
   * на стоянке. Так же взвывает мотор, если дёрнуть селектор против хода.
   */
  const engaged = input.ratio !== 0 && !against;
  const turbine = engaged ? Math.max(0, spin) : was * (1 - NEUTRAL_SLIP);
  const lock = engaged ? smoothstep(turbine, LOCK_FROM, LOCK_FULL) : 0;

  const governor = IDLE_AUTHORITY_NM * clamp((RPM_IDLE - wasRpm) / IDLE_BAND_RPM, 0, 1);
  const source = torqueAt(wasRpm) * pedal - pumpingNm(wasRpm, pedal) + governor;
  const back = CONVERTER_K * (was * was - turbine * turbine);
  const slope = 2 * CONVERTER_K * was * (engaged ? 1 : 1 - (1 - NEUTRAL_SLIP) ** 2);
  const free = Math.max(idleRad, was + (dtS * (source - back)) / (ENGINE_INERTIA + dtS * slope));

  // Замкнутый режим: обороты — это турбина, и ничего больше. Ниже холостых
  // коленвал не опускается (регулятор), выше полосы ограничителя — тоже: там
  // подачи уже нет, а разницу между колесом и коленвалом забирает муфта. Без
  // этого потолка сорвавшееся в воздухе колесо накручивало на тахометре
  // пятнадцать тысяч — обороты, на которых мотора бы уже не было.
  const ceiling = (RPM_MAX + LIMIT_BAND_RPM) * RAD_PER_RPM;
  const locked = clamp(turbine, idleRad, ceiling);
  const lockedRpm = locked / RAD_PER_RPM;
  const lockedNm =
    torqueAt(lockedRpm) * pedal -
    pumpingNm(lockedRpm, pedal) +
    IDLE_AUTHORITY_NM * clamp((RPM_IDLE - lockedRpm) / IDLE_BAND_RPM, 0, 1);

  // Смешиваются выходы двух моделей, а не входы. Подставить смешанные обороты в
  // жидкостную ветвь — значит посчитать трансформатор на оборотах, которых у
  // свободного маховика нет: в зоне смыкания муфта тянет обороты к турбине, а
  // жидкость на этих оборотах отдаёт вдвое меньше, чем на своих. Получалась
  // яма момента ровно там, где машина трогается, и разгон в ней проваливался.
  const crank = free + (locked - free) * lock;
  const fluid = CONVERTER_K * (free * free - turbine * turbine);
  const couple = fluid + (lockedNm - fluid) * lock;
  // Смыкание пакета: на ходу или под газом — единица, на стоянке с отпущенным
  // газом или при передаче против хода — нуль.
  const hooked = engaged
    ? Math.max(
        smoothstep(Math.abs(input.wheelSpeedMs), CREEP_FREE_MS * 0.5, CREEP_FREE_MS),
        clamp(pedal / CREEP_PEDAL, 0, 1),
      )
    : 0;
  const forceN = (couple * hooked * input.ratio * FINAL_DRIVE * DRIVELINE_EFF) / WHEEL_RADIUS_M;

  // Греет и проскальзывание трансформатора, и высокие обороты: и то и другое —
  // газ, не ставший движением.
  const slipRadS = crank - turbine;
  const slip = clamp(slipRadS / Math.max(crank, 1), 0, 1);
  const revs = clamp(crank / (RPM_MAX * RAD_PER_RPM), 0, 1);
  return {
    forceN,
    rpm: crank / RAD_PER_RPM,
    waste: pedal * clamp(slip * 2 + revs * revs, 0, 1),
    lock,
    slipRadS,
  };
}

/**
 * Куда обороты придут, если держать эти условия долго. Нужно там, где спрашивают
 * не про отклик, а про способность: втащит ли эта передача на подъём, хватит ли
 * момента тронуться. Настоящего ответа на такой вопрос у шага нет — только у
 * равновесия, поэтому оно и считается честным прогоном, а не формулой.
 */
export function engineSettle(input: Omit<EngineIn, "dtS">, fromRpm = RPM_IDLE): Engine {
  const dtS = 1 / 120;
  let rpm = fromRpm;
  let out = engineStep(rpm, { ...input, dtS });
  for (let i = 0; i < 600; i++) {
    out = engineStep(rpm, { ...input, dtS });
    rpm = out.rpm;
  }
  return out;
}
