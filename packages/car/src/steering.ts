import { WHEELBASE_M } from "./geometry.js";

/**
 * Руль: не положение, а состояние, у которого своя динамика.
 *
 * Первая версия считала клавишу заданием угла: нажал — угол едет к пределу,
 * отпустил — тем же темпом обратно к нулю. Это не руль, а тумблер, и заметно это
 * именно на скорости: в жизни отпущенный руль возвращается сам и тем быстрее,
 * чем быстрее едешь, а на месте остаётся там, где его бросили. Разница не
 * косметическая — на ней держится вся техника руления: в повороте руль
 * подхватывают, а не выкручивают обратно.
 *
 * Модель самая простая из честных. Руки дают постоянную скорость поворота рейки,
 * колёса — возвращающий момент:
 *
 *     dδ/dt = вход · RACK_RATE − k · δ
 *
 * Возвращает руль не одно, а два разных механизма, и путать их нельзя — они
 * по-разному зависят от скорости и по-разному ведут себя на заднем ходу. Ниже
 * они разобраны по отдельности (`casterRate`, `kingpinRate`).
 *
 * Ни тот, ни другой не имеет отношения к сходу-развалу, хотя спрашивают обычно
 * про них. Развал добавляет боковую силу от наклона колеса, сход подбирает
 * устойчивость на прямой и жрёт резину — но возвращающего момента вокруг оси
 * поворота ни то, ни другое не создаёт. Создаёт его геометрия самой оси: её
 * продольный наклон (кастер) и поперечный (наклон шкворня).
 */
const RACK_RATE = 1.7;
/**
 * Механический предел рейки. До него дело доходит только на ползущей машине: на
 * ходу руль раньше упирается в собственный возврат.
 */
export const STEER_LOCK = 0.5;
/**
 * Боковое ускорение, на которое рассчитан возврат: при полном усилии рук машина
 * выходит примерно на него и не срывается в разворот. Три четверти g — это
 * уверенный поворот на сухом асфальте, дальше начинается снос.
 */
const HOLD_ACCEL_MS2 = 0.75 * 9.81;
/**
 * Жёсткость возврата от следа пятна подобрана так, чтобы равновесие при полном
 * усилии совпало с углом на `HOLD_ACCEL_MS2`: RACK_RATE / (CASTER·v²) = база·a/v².
 * Скорость из равенства уходит — коэффициент получается один на все скорости.
 */
const CASTER = RACK_RATE / (WHEELBASE_M * HOLD_ACCEL_MS2);
/**
 * ### Механизм первый: след пятна контакта (кастер)
 *
 * Ось поворота колеса наклонена вперёд, поэтому пятно контакта тащится позади
 * точки, вокруг которой колесо вращается, — на плечо обката плюс собственный
 * увод пятна внутри шины. Боковая сила приложена в пятне, то есть **за** осью, и
 * потому разворачивает колесо по ходу: увод обнуляется сам. Это тележное колесо,
 * и вся устойчивость руля на скорости — от него.
 *
 * Сила растёт с квадратом скорости, отсюда и `v²`. Но вот что важнее и чего в
 * модели не было: знак момента задаёт **направление катания**, а не скорость. На
 * заднем ходу след становится ведущим — пятно оказывается впереди оси, — и тот
 * же самый механизм из возвращающего превращается в опрокидывающий. Колесо
 * магазинной тележки, которую тянут задом, разворачивается поперёк ровно по этой
 * причине, и руль на заднем ходу ведёт себя так же: он не возвращается к нулю, а
 * уходит от него, и держать его приходится руками.
 *
 * Поэтому здесь `longMs·|longMs|`, а не `v²`: это тот же квадрат, но со знаком
 * направления, и он сам собой обращается в ноль на стоящей машине.
 */
function casterRate(longMs: number): number {
  return CASTER * longMs * Math.abs(longMs);
}
/**
 * Боковое ускорение, на котором передок отдаёт всё. Дальше момент от следа не
 * растёт, сколько угол ни добавляй: не растёт сама сила, а плечо у неё своё.
 *
 * Без этого предела квадрат скорости честен только в линейной зоне шины, а за
 * ней врёт тем сильнее, чем быстрее едешь, — и врёт в одну сторону, к бесконечно
 * жёсткому рулю. Вперёд это почти не видно (полное усилие рук уравновешивается
 * на трёх четвертях g, до предела не доходя), а назад, где след раскачивает,
 * именно это решало, может ли человек вообще удержать руль: на пятидесяти
 * километрах в час назад раскачка обгоняла руки в разы.
 */
const GRIP_ACCEL_MS2 = 9.81;
/** Предельная скорость возврата от следа: сила в пятне кончилась. */
const CASTER_MAX = CASTER * WHEELBASE_M * GRIP_ACCEL_MS2;
/**
 * ### Механизм второй: наклон шкворня
 *
 * Ось поворота наклонена ещё и поперёк, поэтому повёрнутое колесо приподнимает
 * над собой кузов. Вес возвращает его обратно — и делает это независимо от того,
 * куда машина едет и едет ли вообще: работает не сила шины, а нагрузка на
 * колесо. Именно это оставляет рулю подобие центра на заднем ходу и на парковке,
 * когда следа пятна нет или он работает против.
 *
 * Механизм слабее первого — на десятки ньютон-метров против сотен, — поэтому
 * руки его перебивают с запасом, а на скорости он вообще незаметен на фоне
 * квадрата.
 */
const KINGPIN = 0.35;
/**
 * Скорость, с которой шкворень выходит на полную. Стоящее колесо не
 * возвращается: подъём кузова держится трением покоя в неподвижном пятне, и
 * брошенный на парковке руль остаётся где брошен. Стоит машине покатиться — пятно
 * срывается, и вес забирает своё.
 */
const KINGPIN_ROLL_MS = 1.5;

function kingpinRate(longMs: number): number {
  return KINGPIN * Math.min(1, Math.abs(longMs) / KINGPIN_ROLL_MS);
}
/**
 * Как быстро рейка вообще способна переложиться, рад/с.
 *
 * Раньше на этом месте стоял верхний предел жёсткости возврата, и стоял он не
 * там. Задача была одна: на ста километрах в час постоянная времени возврата —
 * три сотых секунды, и руль не возвращается, а щёлкает. Но потолок жёсткости
 * гасит заодно и равновесие: `RACK_RATE/k` перестаёт падать со скоростью, и
 * выше десяти метров в секунду полное усилие рук даёт одиннадцать градусов на
 * любой скорости — что на пятидесяти километрах в час, что на ста тридцати. На
 * ста тридцати это полтора же в развороте от одного нажатия клавиши.
 *
 * Мешают рулю трение в рейке и масса рук — а они ограничивают **скорость**
 * перекладки, а не угол, на котором усилия уравновешиваются. Поэтому жёсткость
 * снова растёт с квадратом скорости, как ей и положено, а ограничение стоит
 * там, где ему место: рейка не переложится быстрее, чем позволяют руки.
 */
const RACK_SLEW = 3;

/**
 * ## Руль отсчитывается не от кузова, а от того, куда едет передняя ось
 *
 * Всё выше молча полагает, что машина едет туда, куда смотрит. Пока держат
 * шины, так и есть, и разница между «углом колёс относительно кузова» и «углом
 * колёс относительно набегающей дороги» лежит в пределах пары градусов. В
 * заносе она равна всему: кузов развёрнут поперёк, передние колёса едут вбок
 * сами по себе, и угол, при котором они катятся ровно, — это уже не ноль.
 *
 * Отсюда две вещи, которых у руля не было и без которых заносом нельзя ни
 * управлять, ни выйти из него.
 *
 * Первая: **руль возвращается не в ноль, а в снос**. Стабилизирующий момент
 * стремится обнулить увод шины, а не угол рейки, — поэтому брошенный в заносе
 * руль сам перекладывается в контрруль, и машина ловит себя. Это не поблажка
 * игроку, это то, что происходит в жизни и почему в заносе руль отпускают.
 *
 * Вторая: **отдельного предела угла больше нет**. Он был нужен, пока равновесие
 * рейки отсчитывалось от нуля: на скорости `RACK_RATE/k` — это те самые
 * полтора-два градуса, и всё, что человек мог сделать клавишей, укладывалось в
 * них, а предел стоял ровно затем, чтобы резкий бросок руля не успел проскочить
 * дальше равновесия. Теперь равновесие отсчитывается от сноса и означает нечто
 * определённое: угол увода передних колёс, на котором постоянное усилие рук
 * уравновешивается стабилизирующим моментом. Выходит около одиннадцати градусов
 * — чуть за пиком шины, то есть «руль до упора» и означает «передок отдал всё».
 * Больше этого рейка не уйдёт сама, а меньше её незачем ограничивать: в заносе
 * ограничивать надо было бы как раз контрруль, а он-то и нужен.
 */

/** Ниже этой скорости снос считается по ней: иначе на ползке нейтраль улетает. */
const NEUTRAL_FLOOR_MS = 3;

/**
 * Куда едет передняя ось относительно кузова, радианы. При таком угле рейки
 * передние колёса катятся без увода вовсе.
 *
 * Знак продольной скорости здесь тоже имеет смысл: колесо катится ровно, когда
 * его плоскость лежит вдоль вектора скорости, а не когда она смотрит вперёд. На
 * заднем ходу вектор развёрнут, и угол, на котором колесо не уводит,
 * оказывается зеркальным — δ = atan(поперёк / вдоль) со знаком, а не по модулю.
 */
export function steerNeutral(latMs: number, longMs: number): number {
  const dir = longMs < 0 ? -1 : 1;
  return Math.atan2(latMs * dir, Math.max(Math.abs(longMs), NEUTRAL_FLOOR_MS));
}

/**
 * Куда руль придёт при постоянном полном усилии рук на этой скорости хода
 * вперёд, отсчитывая от сноса: равновесие рейки против стабилизирующего момента.
 * Механический упор рейки его обрезает — на ползущей машине равновесия нет вовсе.
 */
export function steerLimit(speedMs: number): number {
  const v = Math.abs(speedMs);
  const k = casterRate(v) + kingpinRate(v);
  if (k < 1e-4) return STEER_LOCK;
  return Math.min(STEER_LOCK, RACK_RATE / k);
}

/**
 * Шаг руля.
 *
 *     dδ/dt = вход·RACK_RATE + caster·(neutral − δ) − kingpin·δ
 *
 * След пятна тянет колесо к углу, на котором его не уводит; шкворень — к нулю
 * рейки, потому что вес возвращает не колесо к дороге, а кузов вниз. Разница
 * между этими двумя целями и есть то, почему в заносе брошенный руль сам уходит
 * в контрруль, а на парковке просто отыгрывает к центру.
 *
 * `speedMs` — продольная скорость **со знаком**: на заднем ходу первое слагаемое
 * меняет знак и становится раскачивающим. Тогда `k` может оказаться
 * отрицательным, и экспонента ниже честно растёт вместо того, чтобы затухать:
 * это не срыв решения, а то самое поведение тележки, которую тянут задом.
 * Ограничивают его упор рейки и предельная скорость перекладки.
 *
 * Решение берётся точно по экспоненте, а не шагом Эйлера: на ста километрах в
 * час `k·dt` подбирается к единице, и явный шаг начинает раскачиваться там, где
 * руль обязан успокаиваться. У нуля `k` (стоянка и точка, где два механизма
 * уравновешены) экспонента вырождается, и там считается прямой шаг.
 */
export function steerStep(angle: number, input: number, speedMs: number, dtS: number, neutral = 0): number {
  const drive = Math.max(-1, Math.min(1, input)) * RACK_RATE;
  const caster = casterRate(speedMs);
  const king = kingpinRate(speedMs);
  // За пиком шины след тянет с постоянным усилием, а не пропорционально углу:
  // уравнение остаётся линейным, но жёсткость на этот шаг переходит к шкворню.
  const linear = caster * (neutral - angle);
  const pull = Math.max(-CASTER_MAX, Math.min(CASTER_MAX, linear));
  const held = pull === linear;
  const k = held ? caster + king : king;
  const rate = held ? drive + caster * neutral : drive + pull;
  const free =
    Math.abs(k) * dtS < 1e-4 ? angle + (rate - k * angle) * dtS : rate / k + (angle - rate / k) * Math.exp(-k * dtS);
  const slew = RACK_SLEW * dtS;
  const next = Math.max(angle - slew, Math.min(angle + slew, free));
  return Math.max(-STEER_LOCK, Math.min(STEER_LOCK, next));
}
