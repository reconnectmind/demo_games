import type { Surface } from "@gamespace/env";

/**
 * Шина: как колесо цепляется за землю.
 *
 * Свойства покрытий сюда приходят из среды (`@gamespace/env`), а не задаются
 * здесь: что такое гравий, шину не касается — её дело в том, что из этого
 * выходит в пятне контакта. Раньше словарь покрытий лежал в этом файле, и
 * получалось, что о существовании травы знала шина, а о том, где трава лежит, —
 * дорога, то есть понятие было разрезано ровно посередине.
 *
 * До сих пор сцепления в игре не было вовсе. Продольную силу считала коробка,
 * её обрезали по «мю на массу на же» и делили на четыре; поперечную целиком
 * держал контроллер Rapier по одному числу `frictionSlip`. Из этого следовало
 * всё, что в заезде читалось неправдой: колёса не могли забуксовать, не могли
 * заблокироваться, машина не срывалась в занос и не выезжала из него, а разница
 * между асфальтом и травой сводилась к тому, что на траве всё то же самое, но
 * медленнее.
 *
 * Здесь считается настоящая механика контакта, и вся она стоит на одной мысли:
 * **колесо тянет только потому, что проскальзывает**. Пятно контакта — не
 * зацеп, а резина, которую сдвинули относительно дороги; сила рождается из
 * этого сдвига, растёт вместе с ним до предела сцепления и за пределом падает.
 * Отсюда сразу всё остальное: буксование при слишком большом моменте, юз при
 * слишком сильном тормозе, снос передней оси и занос задней, разный характер на
 * асфальте и на гравии, нагрев от того, что скольжение — это работа трения, и
 * она вся уходит в тепло.
 *
 * Модуль чистый: ни Rapier, ни состояния мира, только числа. Так его считает
 * тест, а не браузер.
 *
 * ## Что во что превращается
 *
 * Продольное проскальзывание — насколько обод обгоняет дорогу:
 *   κ = (ω·R − v) / max(|v|, V_FLOOR)
 * Ноль — колесо катится, плюс — буксует, минус — тащится юзом.
 *
 * Увод — на сколько колесо едет боком относительно того, куда смотрит:
 *   α = atan(v_поперёк / max(|v|, V_FLOOR))
 *
 * Дальше оба сводятся в один вектор проскальзывания, и по его длине берётся
 * коэффициент сцепления. Это и есть «круг сцепления»: одна и та же резина
 * держит либо разгон, либо поворот, либо их сумму по теореме Пифагора — и
 * поэтому в повороте нельзя дать полный газ, а под полным тормозом нельзя
 * повернуть.
 */

/** Пол скорости в знаменателях, м/с. */
const V_FLOOR = 2.5;

/**
 * Форма кривой сцепления — «магическая формула» Пацейки в самом коротком виде.
 *
 * Смысл трёх чисел: `B` — крутизна нарастания у нуля (насколько шина отзывчива
 * на малое проскальзывание), `C` — где кривая заворачивает, `E` — насколько
 * полого она падает за пиком. Подобраны так, чтобы пик пришёлся примерно на
 * тринадцать процентов проскальзывания — туда, где он у дорожной шины, — а за
 * пиком сила не исчезала, а спадала процентов на десять: сорванная шина держит
 * хуже, но держит, иначе первый же срыв был бы необратимым.
 *
 * Место пика важнее, чем кажется. Сдвинь его вдвое дальше — и шина начнёт
 * набирать силу только при заметном буксовании: машина тронется с пробуксовкой
 * на сухом асфальте, а руль будет отзываться с запозданием.
 */
const PACEJKA_B = 14;
const PACEJKA_C = 1.9;
const PACEJKA_E = 0.97;

function pacejka(slip: number): number {
  const bs = PACEJKA_B * slip;
  return Math.sin(PACEJKA_C * Math.atan(bs - PACEJKA_E * (bs - Math.atan(bs))));
}

/**
 * Сколько держит шина, которая уже целиком скользит, — в долях пика.
 *
 * У формулы Пацейки нет дна: за пиком она валится и валится, и на
 * проскальзывании в разы (буксование на месте, юз юзом) отдаёт четверть пика.
 * Так шина себя не ведёт. Пятно контакта делится на цепляющуюся часть и
 * скользящую; с ростом проскальзывания первая исчезает, но вторая никуда не
 * девается — это обычное трение скольжения резины о покрытие, и оно почти не
 * зависит от того, насколько быстро проскальзывает. Поэтому у кривой должен
 * быть пол, и стоит он там, где кинетическое трение резины относительно
 * покоя, — около трёх четвертей.
 *
 * Без пола буксующее колесо тянуло меньше, чем сопротивление грунта под ним,
 * и с травы было не съехать: газ в пол только раскручивал колёса, а машина
 * замедлялась.
 */
const SLIDE_HOLD = 0.74;
/**
 * Проскальзывание, на котором скользит уже половина пятна.
 *
 * Втрое-вчетверо больше того, на котором стоит пик: до пика пятно почти целиком
 * цепляется, за пиком зона скольжения растёт с носка к пятке и к нескольким
 * десятым съедает его целиком.
 */
const SLIDE_HALF = 0.45;

/**
 * Какая доля пятна контакта уже скользит, а не цепляется.
 *
 * Ею живут сразу две вещи: пол кривой (скользящая часть даёт кинетическое
 * трение, и оно никуда не девается) и чёрный след (мажет по дороге ровно
 * скользящая часть, цепляющаяся не мажет ничем).
 */
export function slideShare(slip: number): number {
  const s = slip * slip;
  return s / (s + SLIDE_HALF * SLIDE_HALF);
}

/** Пик сырой формулы: от него отмеряется пол. */
const PACEJKA_RAW = (() => {
  let peak = 0;
  for (let s = 0; s <= 2; s += 0.001) peak = Math.max(peak, pacejka(s));
  return peak;
})();

export function tireCurve(slip: number): number {
  const s = Math.abs(slip);
  return Math.max(pacejka(s), PACEJKA_RAW * SLIDE_HOLD * slideShare(s));
}

/**
 * Наклон кривой в этой точке: насколько сила откликается на добавку
 * проскальзывания, в долях предела.
 *
 * Нужен неявному шагу ниже, и нужен именно местный, а не в нуле. У нуля кривая
 * почти отвесна, за пиком — полога и уже идёт вниз. Пока шаг брал наклон в нуле
 * на любом проскальзывании, колесо было численно приколочено к пределу
 * сцепления: как только оно пыталось сорваться, поправка делила его ускорение на
 * полсотни, и буксование не начиналось никогда. Ни тронуться с пробуксовкой, ни
 * сорвать зад в повороте на асфальте было нельзя не потому, что не хватало
 * момента, а потому, что так считалось.
 *
 * Разность вместо производной — сознательно: у «магической формулы» производная
 * берётся аналитически, но выражение получается длиной в строку, в которой
 * нельзя увидеть ошибку. Здесь же видно ровно то, что написано.
 */
export function tireSlope(slip: number): number {
  const h = 1e-4;
  const s = Math.abs(slip);
  const lo = Math.max(0, s - h);
  const hi = s + h;
  return (tireCurve(hi) - tireCurve(lo)) / (hi - lo);
}

/**
 * Пик кривой: по нему нормируется сцепление, чтобы `grip` покрытия читался как
 * привычное «мю» — единица на сухом асфальте, а не «единица, умноженная на
 * случайный множитель формы».
 */
const PACEJKA_PEAK = (() => {
  let peak = 0;
  for (let s = 0; s <= 2; s += 0.001) peak = Math.max(peak, tireCurve(s));
  return peak;
})();

/**
 * Нагрузка, при которой шина держит своё номинальное «мю». Взята как четверть
 * снаряжённой массы: на ровной дороге столько и приходится на колесо.
 */
const LOAD_REF_N = (2100 * 9.81) / 4;
/**
 * Падение сцепления с ростом нагрузки. У настоящей шины удвоение нагрузки даёт
 * заметно меньше удвоения силы, и это не мелочь для игры: именно поэтому
 * перегруженное наружное колесо в повороте срывается первым, а машина в
 * повороте держит хуже, чем на прямой при той же сумме нагрузок.
 */
const LOAD_FALL = 0.16;

export function loadFactor(loadN: number): number {
  const ratio = Math.max(0.05, loadN / LOAD_REF_N);
  return Math.max(0.45, 1 - LOAD_FALL * (ratio - 1));
}

/** Температура воздуха и она же — начальная температура шины, °C. */
export const TIRE_COLD_C = 20;
/** Где шина держит лучше всего, °C. */
const TIRE_BEST_C = 85;
/** Ширина рабочего окна, °C: на этом отступе от лучшей теряется `TEMP_FALL`. */
const TIRE_SPAN_C = 65;
/** Сколько сцепления теряет шина на краю окна. */
const TEMP_FALL = 0.22;

/**
 * Сцепление от температуры — парабола с вершиной в рабочем окне.
 *
 * Холодная шина скользит, и это заметно на первых секундах заезда; перегретая
 * скользит тоже, и это то, чем кончается долгий срыв. Между ними — полка, на
 * которой машина едет как задумано.
 */
export function tempFactor(tempC: number): number {
  const off = (tempC - TIRE_BEST_C) / TIRE_SPAN_C;
  return Math.max(0.55, 1 - TEMP_FALL * off * off);
}

/**
 * Нагрев от скольжения и остывание набегающим воздухом.
 *
 * Греет ровно мощность трения — сила на скорость скольжения, — потому что вся
 * она и есть тепло. Остывает шина тем быстрее, чем быстрее едешь, и это делает
 * нагрев самоограниченным: долго ехать боком нельзя, но и остыть на прямой
 * можно.
 *
 * Числа — это теплоёмкость и постоянная остывания. Греется не вся шина, а
 * верхний слой протектора, поэтому теплоёмкость взята килограммом резины, а не
 * всеми десятью: иначе секунда буксования не сдвинула бы температуру вовсе.
 * Остывание, наоборот, медленное — десятки секунд, — и от этого нагрев успевает
 * накопиться за поворот и не успевает исчезнуть между поворотами.
 */
const HEAT_PER_J = 1 / 2500;
const COOL_PER_S = 0.02;
const COOL_PER_MS = 0.0012;

export function heatStep(tempC: number, frictionW: number, speedMs: number, dtS: number): number {
  const cool = (COOL_PER_S + COOL_PER_MS * Math.abs(speedMs)) * (tempC - TIRE_COLD_C);
  return tempC + (frictionW * HEAT_PER_J - cool) * dtS;
}

/**
 * ## Чёрная полоса на асфальте
 *
 * Резину стирает работа трения — та же самая мощность, что греет шину. Это не
 * совпадение и не экономия: скольжение под нагрузкой есть ровно один процесс, и
 * часть его энергии уходит в тепло, а часть отрывает от протектора вещество.
 * Поэтому износ считается от `frictionW`, а не от проскальзывания: колесо,
 * проскальзывающее вхолостую без нагрузки, ничего не стирает, а гружёное под
 * тем же проскальзыванием стирает много.
 *
 * Но стёртая резина не всегда остаётся на дороге, и вот здесь нужна температура.
 * Холодная резина крошится в пыль: её уносит, а след получается серым и еле
 * заметным — это тот самый износ, который съедает протектор за десятки тысяч
 * километров, ничего на дороге не оставляя. Горячая размягчается и мажет:
 * оторванное прилипает к асфальту плёнкой, и вот она-то и есть чёрная полоса.
 *
 * Температура при этом нужна не та, которой считается сцепление. `tempC` — это
 * толща протектора, килограмм резины, и она набирает свои полсотни градусов за
 * секунды. Мажет же поверхность, микроны, и она в скольжении раскалена куда
 * сильнее толщи: весь тепловой поток трения входит именно через неё, и перепад
 * на этих микронах — сотня градусов при киловаттах в пятне. Это обычная
 * «вспышечная» температура контакта, и без неё модель говорит неправду в обе
 * стороны: свежая шина не чернила бы асфальт никогда, а прогретая чернила бы
 * его просто от того, что прогрета.
 */

/**
 * Насколько поверхность пятна горячее толщи протектора при такой мощности
 * трения, °C на ватт. Двадцать киловатт дают восемьдесят градусов перепада.
 */
const FLASH_PER_W = 0.004;

/** Температура самой поверхности пятна: толща плюс перепад от потока, °C. */
export function flashC(tempC: number, frictionW: number): number {
  return tempC + FLASH_PER_W * Math.max(0, frictionW);
}

/** Ниже этой температуры резина крошится в пыль и следа не оставляет, °C. */
const SMEAR_FROM_C = 55;
/** Выше — мажет всем, что оторвалось, °C. */
const SMEAR_FULL_C = 100;

/** Какая доля оторванной резины остаётся на дороге при этой температуре. */
export function smearAt(surfaceC: number): number {
  const t = Math.max(0, Math.min(1, (surfaceC - SMEAR_FROM_C) / (SMEAR_FULL_C - SMEAR_FROM_C)));
  return t * t * (3 - 2 * t);
}

/**
 * Мощность трения, при которой горячая шина оставляет насыщенно чёрный след, Вт.
 * Порядок величины виден из простого: полтонны на колесе, коэффициент около
 * единицы, скольжение метров пять в секунду — двадцать с лишним киловатт.
 */
const MARK_FULL_W = 22_000;

/**
 * Ниже этого следа нет вовсе. Порог не оптимизация, а правда: резина стирается
 * при любом скольжении, но пока она стирается в пыль, дорога остаётся чистой, и
 * бледная серая тень за спокойно едущей машиной была бы враньём.
 */
const MARK_FAINT = 0.06;

/**
 * Насколько чёрен след под этим колесом прямо сейчас: 0 — ничего, 1 — смоль.
 *
 * Проскальзывание входит сюда не мерой силы, а мерой того, какая часть пятна
 * скользит. Мажет только она. Без этого множителя чернить дорогу начинало
 * колесо, которое просто быстро едет под нагрузкой: работа трения на сотне
 * километров в час велика и при трёх процентах проскальзывания, хотя пятно там
 * держит, а не скользит, и оставлять ему нечего.
 */
export function markAt(frictionW: number, tempC: number, surface: Surface, slip: number): number {
  const rate = Math.min(1, Math.max(0, frictionW) / MARK_FULL_W);
  const black =
    rate *
    slideShare(slip) *
    smearAt(flashC(tempC, frictionW)) *
    Math.max(0, Math.min(1, surface.keeps));
  return black < MARK_FAINT ? 0 : black;
}

/**
 * Момент инерции колеса, кг·м². Колесо в сборе — не диск, масса у него ближе к
 * ободу, поэтому берётся не `mR²/2`, а немного больше. К этому числу физика
 * добавляет приведённую инерцию трансмиссии (`drivelineInertia`).
 */
export const WHEEL_INERTIA = 1.6;

export interface TireStep {
  /** Угловая скорость колеса, рад/с. */
  omega: number;
  /** Температура шины, °C. */
  tempC: number;
  /** Нормальная нагрузка, Н. */
  loadN: number;
  /** Скорость земли под колесом вдоль его плоскости, м/с. */
  alongMs: number;
  /** То же поперёк плоскости колеса, м/с. */
  acrossMs: number;
  /** Момент от двигателя, Н·м. */
  driveNm: number;
  /** Момент тормоза, Н·м: всегда против вращения. */
  brakeNm: number;
  /** Инерция колеса вместе с приведённой инерцией трансмиссии, кг·м². */
  inertia: number;
  radiusM: number;
  surface: Surface;
  dtS: number;
}

export interface TireOut {
  /** Сила вдоль плоскости колеса, Н: плюс — толкает вперёд. */
  alongN: number;
  /** Сила поперёк, Н. */
  acrossN: number;
  omega: number;
  tempC: number;
  slipRatio: number;
  slipAngle: number;
  /**
   * Насколько шина за пределом сцепления: 0 — держит, 1 — на пике, больше —
   * срыв. По этому числу и рисуется дым, и свистит резина.
   */
  slide: number;
  /** Мощность трения в пятне, Вт: она же греет шину, она же стирает резину. */
  frictionW: number;
  /** Насколько чёрный след остаётся под колесом: 0 — никакого, 1 — смоль. */
  mark: number;
}

/**
 * Один шаг шины.
 *
 * Порядок важен: сила считается по проскальзыванию, накопленному к началу шага,
 * и только потом ею же обновляется вращение колеса. Обратный порядок дал бы
 * колесу останавливаться раньше, чем оно успеет оттолкнуться.
 */
export function tireStep(step: TireStep): TireOut {
  const { radiusM, surface, dtS } = step;
  const speed = Math.max(Math.abs(step.alongMs), V_FLOOR);
  const slipAngle = Math.atan2(step.acrossMs, speed);
  // Поперечное проскальзывание берётся тангенсом угла: в одних единицах с
  // продольным, иначе их нельзя складывать в один вектор.
  const sy = Math.tan(slipAngle);

  const mu = surface.grip * loadFactor(step.loadN) * tempFactor(step.tempC);
  const capacity = mu * Math.max(0, step.loadN);

  /** Сила в пятне по продольному проскальзыванию, поперечное — из замыкания. */
  const grab = (sx: number) => {
    const slide = Math.hypot(sx, sy);
    if (slide < 1e-9) return { slide, along: 0, across: 0, force: 0 };
    const force = (capacity * tireCurve(slide)) / PACEJKA_PEAK;
    return { slide, along: (force * sx) / slide, across: (-force * sy) / slide, force };
  };

  const was = (step.omega * radiusM - step.alongMs) / speed;
  const first = grab(was);

  /**
   * Вращение колеса: момент двигателя минус тормоз минус отдача дороги.
   *
   * Отдача берётся неявно, и без этого модель не живёт. Шина у нуля
   * проскальзывания очень жёсткая: изменение угловой скорости на единицу меняет
   * силу на десятки килоньютонов, тем сильнее, чем медленнее едешь. Явный шаг в
   * шестидесятую секунды такую жёсткость не держит — колесо на малой скорости
   * начинает раскачиваться между «буксует» и «тормозит», и машина вместо
   * трогания подпрыгивает. Поправка ниже — линеаризация силы по угловой
   * скорости: шаг делится на то, насколько сила успеет измениться за него.
   *
   * Тормоз обязан войти в тот же числитель, а не вычитаться потом отдельно.
   * Иначе отдача дороги оказывается ослаблена поправкой, а тормоз — нет, и
   * колесо встаёт юзом от любого нажатия, каким бы слабым оно ни было: та самая
   * жёсткость, ради которой поправка и введена, начинает работать против шины.
   *
   * Наклон берётся местный и обрезается снизу нулём. Обрезка и есть то, что
   * пускает колесо в срыв: за пиком добавка проскальзывания силы уже не даёт,
   * держать колесу не за что, и поправка обязана выключиться, иначе она держит
   * его вместо дороги. Ниже нуля наклон не пускают по другой причине —
   * отрицательный он не успокаивал бы шаг, а разгонял.
   */
  const spinDir = step.omega !== 0 ? Math.sign(step.omega) : Math.sign(step.alongMs);
  const brakeNm = Math.max(0, step.brakeNm) * spinDir;
  const stiff = (capacity * Math.max(0, tireSlope(first.slide))) / PACEJKA_PEAK;
  const soften = 1 + (dtS * radiusM * radiusM * stiff) / (step.inertia * speed);
  const net = step.driveNm - brakeNm - first.along * radiusM;
  let omega = step.omega + (((net / step.inertia) * dtS) / soften);
  // Тормоз не умеет крутить колесо назад: он его останавливает. Без этой границы
  // колесо на малом шаге перескакивает через ноль и «вращается» в обратную
  // сторону, а машина от этого дёргается вперёд.
  if (brakeNm !== 0 && Math.sign(omega) === -spinDir) omega = 0;

  /**
   * Машине отдаётся сила на проскальзывании **конца** шага, а не начала. Это не
   * педантизм: неявный шаг выше как раз и решает, каким проскальзывание станет к
   * концу, и если колесу отдать одно, а машине другое, то разница осядет
   * паразитным сопротивлением. Оно тем больше, чем медленнее едешь, и на
   * трогании с места съедало пятую часть разгона.
   */
  const slipRatio = (omega * radiusM - step.alongMs) / speed;
  const now = grab(slipRatio);
  let alongN = now.along;

  // Сопротивление качению — не трение скольжения, а потери в самой шине и в
  // грунте под ней, поэтому оно живёт отдельно от круга сцепления.
  const rolling = (surface.roll + surface.dig) * Math.max(0, step.loadN);
  if (Math.abs(step.alongMs) > 0.05) alongN -= Math.sign(step.alongMs) * rolling;

  // Греет и скольжение, и качение: сопротивление качению — это работа, которую
  // шина тратит на собственное сминание, и она тоже целиком уходит в тепло.
  // Без второго слагаемого шина на прямой оставалась бы ледяной.
  const slipMs = Math.hypot(omega * radiusM - step.alongMs, step.acrossMs);
  // Мощность трения скольжения — она и стирает резину. Качение из неё исключено
  // нарочно: оно тоже греет, но следа не оставляет, потому что там ничего не
  // скользит, а просто мнётся.
  const frictionW = now.force * slipMs;
  const tempC = heatStep(step.tempC, frictionW + rolling * Math.abs(step.alongMs), step.alongMs, dtS);

  return {
    alongN,
    acrossN: now.across,
    omega,
    tempC,
    slipRatio,
    slipAngle,
    slide: now.slide,
    frictionW,
    mark: markAt(frictionW, tempC, surface, now.slide),
  };
}
