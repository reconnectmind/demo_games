/**
 * Сколько пыли поднимает колесо и какая она.
 *
 * Раньше съезд на обочину показывался тем, что во всей сцене втрое густел туман.
 * Это и была та «странность с небом»: туман в Babylon — свойство воздуха вообще,
 * он красит всю даль разом, и стоило колесу коснуться травы, как горизонт
 * превращался в серую стену, а через полметра обратно. Пыль так себя не ведёт.
 * Она поднимается там, где шина рвёт грунт, висит секунду и оседает — то есть
 * принадлежит колесу, а не миру.
 *
 * Здесь только правило, без единой частицы: сколько поднимается и какого цвета.
 * Само облако рисует `plume.ts` — ровно так же, как решение о черноте следа
 * принимает шина в `tire.ts`, а ленту на дорогу кладёт `marks.ts`.
 *
 * Мелочь с грунта поднимает и катящееся колесо — потому за машиной по гравию
 * тянется шлейф, — но по-настоящему её вышибает проскальзывание, поэтому в рыхлое
 * сорвавшееся колесо зарывается с облаком. На асфальте рвать нечего: там дымит
 * сама резина, и дым другой — светлый, редкий и лезущий вверх, а не в стороны.
 */

import type { SurfaceKind } from "@gamespace/env";

/** Как ведёт себя то, что поднимается из-под колеса на этом покрытии. */
export interface Puff {
  /** Цвет облачка: цвет грунта, выцветший — взвесь всегда светлее насыпи. */
  color: [number, number, number];
  /** Сколько рыхлого есть вообще: асфальту рвать нечего, там только резина. */
  loose: number;
  /** Какую долю поднимает уже одно качение — остальное вышибает срыв. */
  rolling: number;
  /** Сколько облачко живёт, секунды. */
  lifeS: number;
  /** Как быстро оно всплывает, м/с: дым легче пыли. */
  riseMs: number;
  /** Размер облачка в начале и в конце жизни, метры. */
  size: [number, number];
}

export const PUFFS: Record<SurfaceKind, Puff> = {
  // Дым от резины: его поднимает только срыв, зато он светлый и тянется вверх.
  asphalt: { color: [0.66, 0.65, 0.66], loose: 0.5, rolling: 0, lifeS: 1.1, riseMs: 1.1, size: [0.45, 2.2] },
  gravel: { color: [0.68, 0.62, 0.52], loose: 1, rolling: 0.35, lifeS: 1, riseMs: 0.55, size: [0.35, 1.9] },
  // Дёрн держит землю: трава пылит меньше гравия, зато мажет темнее.
  grass: { color: [0.52, 0.5, 0.36], loose: 0.7, rolling: 0.22, lifeS: 0.9, riseMs: 0.5, size: [0.35, 1.7] },
};

/** Сколько облачков в секунду даёт колесо на полной работе. */
export const RATE_MAX = 70;
/** Работа качения: с какой скорости, м/с, шлейф выходит на полную. */
const ROLL_FULL_MS = 16;
/**
 * За каким проскальзыванием колесо считается сорванным. Единица — это пик кривой
 * шины, дальше начинается скольжение (см. `tire.ts`), оттуда же и пыль.
 */
const SLIDE_FROM = 0.9;
const SLIDE_FULL = 2.2;
/** Ниже этого шага пыли нет вовсе: стоящая машина не пылит. */
const RATE_MIN = 2;

/** Сколько облачков в секунду поднимает колесо на этом покрытии. */
export function dustRate(puff: Puff, slide: number, speedMs: number): number {
  const roll = puff.rolling * Math.min(1, Math.abs(speedMs) / ROLL_FULL_MS);
  const torn = Math.min(1, Math.max(0, (slide - SLIDE_FROM) / (SLIDE_FULL - SLIDE_FROM)));
  // Сорванное колесо пылит и на месте, катящееся — только пока катится.
  const work = puff.loose * (roll + (1 - puff.rolling) * torn);
  const rate = RATE_MAX * Math.min(1, work);
  return rate < RATE_MIN ? 0 : rate;
}
